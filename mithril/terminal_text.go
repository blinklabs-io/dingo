package mithril

import (
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"
)

// EscapeText returns s with every character that could act on a terminal
// replaced by a visible escape sequence. Aggregator responses are
// remote-controlled, so text taken from them must pass through here before
// it reaches an operator's terminal.
//
// ESC, other C0 and C1 control characters, newlines, bidirectional and other
// format characters, and invalid UTF-8 are escaped; printable text is
// returned unchanged.
func EscapeText(s string) string {
	if !needsEscape(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s) + 16)
	for i := 0; i < len(s); {
		r, size := utf8.DecodeRuneInString(s[i:])
		switch {
		case r == utf8.RuneError && size <= 1:
			fmt.Fprintf(&b, `\x%02x`, s[i])
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == ' ' || unicode.IsPrint(r):
			b.WriteRune(r)
		case r < 0x100:
			fmt.Fprintf(&b, `\x%02x`, r)
		case r < 0x10000:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			fmt.Fprintf(&b, `\U%08x`, r)
		}
		i += size
	}
	return b.String()
}

func needsEscape(s string) bool {
	for i := 0; i < len(s); {
		r, size := utf8.DecodeRuneInString(s[i:])
		if (r == utf8.RuneError && size <= 1) ||
			(r != ' ' && !unicode.IsPrint(r)) {
			return true
		}
		i += size
	}
	return false
}
